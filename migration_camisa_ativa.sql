-- Se houver duplicatas, esta consulta lista os grupos que exigem revisão manual.
SELECT COD_ESCOLINHA, NUMERO_CAMISA, COUNT(*) AS QUANTIDADE
FROM TB_ALUNO
WHERE STATUS = 'ATIVO' AND NUMERO_CAMISA IS NOT NULL
GROUP BY COD_ESCOLINHA, NUMERO_CAMISA
HAVING COUNT(*) > 1;

DELIMITER //
BEGIN NOT ATOMIC
    IF EXISTS (
        SELECT 1 FROM TB_ALUNO
        WHERE STATUS = 'ATIVO' AND NUMERO_CAMISA IS NOT NULL
        GROUP BY COD_ESCOLINHA, NUMERO_CAMISA HAVING COUNT(*) > 1
    ) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Camisas duplicadas: revise os grupos listados antes de reaplicar.';
    END IF;
END//
DELIMITER ;

-- O índice único também protege contra mudanças concorrentes durante o ALTER.
ALTER TABLE TB_ALUNO
    ADD COLUMN IF NOT EXISTS NUMERO_CAMISA_ATIVO INT GENERATED ALWAYS AS (CASE WHEN STATUS = 'ATIVO' THEN NUMERO_CAMISA END) STORED,
    ADD UNIQUE KEY IF NOT EXISTS UQ_ALUNO_CAMISA_ATIVA (COD_ESCOLINHA, NUMERO_CAMISA_ATIVO);

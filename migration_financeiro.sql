-- Execute uma vez em bancos existentes que ainda não possuem TB_FINANCEIRO.
-- Esta migração é aditiva e preserva os demais dados do sistema.
CREATE TABLE IF NOT EXISTS TB_FINANCEIRO (
    COD_LANCAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    COD_ESCOLINHA INT NOT NULL,
    COD_ALUNO INT NULL,
    TIPO ENUM('RECEITA','DESPESA') NOT NULL,
    CATEGORIA ENUM('MENSALIDADE','MATRICULA','UNIFORME','OUTROS') NOT NULL DEFAULT 'OUTROS',
    DESCRICAO VARCHAR(150) NOT NULL,
    COMPETENCIA DATE NULL,
    VALOR DECIMAL(10,2) NOT NULL,
    VENCIMENTO DATE NOT NULL,
    DATA_PAGAMENTO DATE NULL,
    STATUS ENUM('PENDENTE','PAGO','CANCELADO','ATRASADO','NAO_PAGO') NOT NULL DEFAULT 'PENDENTE',
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UK_MENSALIDADE (COD_ESCOLINHA,COD_ALUNO,CATEGORIA,COMPETENCIA),
    INDEX IDX_FINANCEIRO_PERIODO (COD_ESCOLINHA,VENCIMENTO,STATUS),
    FOREIGN KEY (COD_ESCOLINHA) REFERENCES TB_ESCOLINHA(COD_ESCOLINHA) ON DELETE CASCADE,
    FOREIGN KEY (COD_ALUNO) REFERENCES TB_ALUNO(COD_ALUNO) ON DELETE RESTRICT
);
